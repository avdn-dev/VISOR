          line: 20,
          column: 3,
          severity: .error),
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "multipleBindings"),
          message: "declare each VISOR State field in a separate var declaration",
          line: 21,
          column: 3,
          severity: .error),
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "nonIdentifierPattern"),
          message: "VISOR State fields require a single identifier pattern",
          line: 22,
          column: 3,
          severity: .error),
      ],
      macros: stateFieldPolicyMacro)
  }

  @Test
  func `A rejected field suppresses actual ViewModel synthesis`() {
    assertMacroExpansion(
      """
      @MainActor
      @ViewModel
      final class InvalidViewModel {
        final class State {
          var valid = 0
          @ObservationIgnored nonisolated var invalid = 0
        }
      }
      """,
      expandedSource: """
      @MainActor
      final class InvalidViewModel {
        @MainActor @VISOR._ViewModelState
        final class State {
          var valid = 0
          @ObservationIgnored nonisolated var invalid = 0
        }
      }
      """,
      macros: viewModelMacro)
  }

  @Test
  func `A rejected field emits no partial State conformance`() {
    assertMacroExpansion(
      """
      @StateShape
      final class State {
        var valid = 0
        @ObservationIgnored nonisolated(unsafe) var invalid = 0
      }
      """,
      expandedSource: """
      final class State {
        var valid = 0
        @ObservationIgnored nonisolated(unsafe) var invalid = 0
      }
      """,
      diagnostics: [
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "ignoredIsolationModifier"),
          message: "VISOR State field 'invalid' cannot combine @ObservationIgnored with nonisolated(unsafe)",
          line: 4,
          column: 3,
          severity: .error),
      ],
      macros: stateShapeMacro)
  }

  @Test
  func `Bound rejects unsupported placement and declaration`() {
    assertMacroExpansion(
      """
      final class NotAViewModel {
        @Bound(source: \\NotAViewModel.source)
        var value = 0
      }
      """,
      expandedSource: """
      final class NotAViewModel {
        var value = 0
      }
      """,
      diagnostics: [
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "invalidBoundPlacement"),
          message: "@Bound is only supported on a direct member of @ViewModel.State",
          line: 2,
          column: 3,
          severity: .error),
      ],
      macros: sourceEntryMacros)

    assertMacroExpansion(
      """
      @ViewModel
      final class ExampleViewModel {
        final class State {
          @Bound(source: \\ExampleViewModel.source)
          var value: Int { 0 }
        }
      }
      """,
      expandedSource: """
      @ViewModel
      final class ExampleViewModel {
        final class State {
          var value: Int { 0 }
        }
      }
      """,
      diagnostics: [
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "invalidBoundDeclaration"),
          message: "@Bound requires one ordinary stored State property and a source selection",
          line: 4,
          column: 5,
          severity: .error),
      ],
      macros: sourceEntryMacros)
  }

  @Test
  func `Reaction rejects unsupported placement and signature`() {
    assertMacroExpansion(
      """
      @ViewModel
      final class ExampleViewModel {
        @Reaction(source: \\ExampleViewModel.source)
        func changed(_ first: Int, _ second: Int) {}
      }
      """,
      expandedSource: """
      @ViewModel
      final class ExampleViewModel {
        func changed(_ first: Int, _ second: Int) {}
      }
      """,
      diagnostics: [
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "invalidReactionDeclaration"),
          message: "@Reaction requires one nonthrowing Void method parameter and a source selection",
          line: 3,
          column: 3,
          severity: .error),
      ],
      macros: sourceEntryMacros)

    assertMacroExpansion(
      """
      extension ExampleViewModel {
        @Reaction(source: \\ExampleViewModel.source)
        func changed(_ value: Int) {}
      }
      """,
      expandedSource: """
      extension ExampleViewModel {
        func changed(_ value: Int) {}
      }
      """,
      diagnostics: [
        DiagnosticSpec(
          id: MessageID(
            domain: "V11CompileProof",
            id: "invalidReactionPlacement"),
          message: "@Reaction is only supported on a direct @ViewModel member",
          line: 2,
          column: 3,
          severity: .error),
      ],
      macros: sourceEntryMacros)
  }
}
